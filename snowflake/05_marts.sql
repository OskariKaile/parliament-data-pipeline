USE ROLE PIPELINE_ROLE;
USE WAREHOUSE PIPELINE_WH;
USE DATABASE PARLIAMENT;

-- One row per item, German source + English AI fields + lead author
CREATE OR REPLACE VIEW MART.V_BUSINESS AS
WITH lead_author AS (
    SELECT a.BUSINESS_ID, a.AUTHOR_TYPE, a.PARTY, a.CANTON,
           m.FIRST_NAME || ' ' || m.LAST_NAME AS AUTHOR_NAME
      FROM CORE.BUSINESS_AUTHOR a
      LEFT JOIN CORE.MEMBER m ON m.MEMBER_ID = a.MEMBER_ID
   QUALIFY ROW_NUMBER() OVER (PARTITION BY a.BUSINESS_ID
                              ORDER BY IFF(a.AUTHOR_TYPE = 'member', 0, 1), a.MEMBER_ID) = 1
)
SELECT b.BUSINESS_ID, b.SHORT_NUMBER, b.BUSINESS_TYPE, b.BUSINESS_TYPE_NAME,
       b.TITLE_DE, e.TITLE_EN, e.SUMMARY_EN, e.IS_DIGITAL, e.TOPICS_PREDICTED,
       b.TAG_NAMES AS TOPICS_OFFICIAL_DE, b.TAG_COUNT,
       b.STATUS, b.DEPARTMENT, b.COUNCIL, b.SUBMITTED_ON,
       DATE_TRUNC('month', b.SUBMITTED_ON) AS SUBMITTED_MONTH,
       la.AUTHOR_TYPE, la.AUTHOR_NAME, la.PARTY, la.CANTON,
       b.BODY_CHARS, b.SOURCE_URL, b.LAST_CHANGED_AT, e.ENRICHED_AT
  FROM CORE.BUSINESS b
  LEFT JOIN AI.BUSINESS_ENRICHED e ON e.BUSINESS_ID = b.BUSINESS_ID
  LEFT JOIN lead_author la ON la.BUSINESS_ID = b.BUSINESS_ID;

-- Items per month and official topic
CREATE OR REPLACE VIEW MART.V_TOPIC_MONTHLY AS
SELECT DATE_TRUNC('month', b.SUBMITTED_ON) AS MONTH, t.TOPIC_EN, COUNT(*) AS ITEMS
  FROM CORE.BUSINESS b
  JOIN CORE.BUSINESS_TOPIC t ON t.BUSINESS_ID = b.BUSINESS_ID
 GROUP BY 1, 2;

-- Which topics each party pushes (share of that party's tagged items)
CREATE OR REPLACE VIEW MART.V_PARTY_TOPIC AS
WITH x AS (
    SELECT v.PARTY, t.TOPIC_EN, COUNT(DISTINCT v.BUSINESS_ID) AS ITEMS
      FROM MART.V_BUSINESS v
      JOIN CORE.BUSINESS_TOPIC t ON t.BUSINESS_ID = v.BUSINESS_ID
     WHERE v.AUTHOR_TYPE = 'member' AND v.PARTY IS NOT NULL
     GROUP BY 1, 2
)
SELECT PARTY, TOPIC_EN, ITEMS,
       ROUND(ITEMS / SUM(ITEMS) OVER (PARTITION BY PARTY), 4) AS SHARE_OF_PARTY
  FROM x;

-- AI / data / digitalisation watchlist (Cortex AI_FILTER = TRUE)
CREATE OR REPLACE VIEW MART.V_WATCHLIST AS
SELECT BUSINESS_ID, SHORT_NUMBER, BUSINESS_TYPE_NAME, SUBMITTED_ON, TITLE_EN, TITLE_DE,
       SUMMARY_EN, AUTHOR_NAME, PARTY, CANTON, STATUS, SOURCE_URL, ENRICHED_AT
  FROM MART.V_BUSINESS
 WHERE IS_DIGITAL;

-- Pipeline health: latest DQ result per check, latest load per table
CREATE OR REPLACE VIEW MART.V_DQ_LATEST AS
SELECT *
  FROM OPS.DQ_RESULTS
QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY, CHECK_NAME ORDER BY INSERTED_AT DESC) = 1;

CREATE OR REPLACE VIEW MART.V_LOAD_LATEST AS
SELECT *
  FROM OPS.LOAD_LOG
QUALIFY ROW_NUMBER() OVER (PARTITION BY TARGET_TABLE ORDER BY LOGGED_AT DESC) = 1;

CREATE OR REPLACE VIEW MART.V_KPIS AS
SELECT
    (SELECT COUNT(*) FROM CORE.BUSINESS)                                   AS ITEMS_TOTAL,
    (SELECT COUNT(*) FROM CORE.BUSINESS
      WHERE SUBMITTED_ON >= DATEADD('day', -30, CURRENT_DATE()))           AS ITEMS_LAST_30D,
    (SELECT COUNT(*) FROM AI.BUSINESS_ENRICHED)                            AS ITEMS_ENRICHED,
    (SELECT COUNT_IF(IS_DIGITAL) FROM AI.BUSINESS_ENRICHED)                AS ITEMS_DIGITAL,
    (SELECT COUNT(*) FROM CORE.MEMBER WHERE ACTIVE)                        AS MEMBERS_ACTIVE,
    (SELECT MAX(INSERTED_AT) FROM OPS.DQ_RESULTS)                          AS LAST_ALTERYX_RUN,
    (SELECT COUNT_IF(STATUS = 'FAIL') FROM MART.V_DQ_LATEST)               AS DQ_CHECKS_FAILING;
