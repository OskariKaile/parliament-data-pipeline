"""Render snowflake/04_cortex_eval.sql from reference/topics.csv.

The 28 topic labels appear several times in the eval SQL (AI_CLASSIFY label
list, label+description objects, JSON-schema enum). Generating them from the
same CSV that Alteryx loads keeps the SQL and the reference data in sync.

    python tools/gen_eval_sql.py
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
rows = list(csv.DictReader(open(ROOT / "reference" / "topics.csv", encoding="utf-8")))


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


labels = "[" + ",\n                 ".join(
    ", ".join(q(r["TOPIC_EN"]) for r in rows[i:i + 5]) for i in range(0, len(rows), 5)
) + "]"
objs = "[\n" + ",\n".join(
    "                    {'label': %s, 'description': %s}" % (q(r["TOPIC_EN"]), q(r["TOPIC_DESCRIPTION_EN"]))
    for r in rows
) + "\n                ]"
topic_list = "\\n".join("- " + r["TOPIC_EN"].replace("'", "''") for r in rows)
TASK = ("Assign the policy topics of a Swiss parliamentary item (German text). "
        "Most items have two or three topics.")

sql = f"""-- =====================================================================
-- 04_cortex_eval.sql  (run as PIPELINE_ROLE, after the first Alteryx load)
-- GENERATED by tools/gen_eval_sql.py from reference/topics.csv. Edit there.
--
-- Question: how well does Cortex AI_CLASSIFY reproduce the official topic
-- tags that Parliament Services assign to every item?
-- Sample: 300 tagged items (deterministic, so every variant sees the same).
-- Variants:
--   v0_majority_baseline   always the 2 most common topics (the floor)
--   v1_classify_labels     AI_CLASSIFY, labels only
--   v2_classify_described  AI_CLASSIFY, labels + 25-word descriptions
--   v3_classify_task       v2 + task_description
--   v4_complete_json       AI_COMPLETE + JSON schema (enum of the 28 topics)
-- Metrics: micro precision / recall / F1, exact-set match, labels per item.
-- Results are written up in docs/CORTEX_EVAL.md.
-- =====================================================================
USE ROLE PIPELINE_ROLE;
USE WAREHOUSE PIPELINE_WH;
USE DATABASE PARLIAMENT;

CREATE OR REPLACE TABLE AI.EVAL_SAMPLE AS
SELECT BUSINESS_ID
  FROM CORE.BUSINESS
 WHERE TAG_COUNT > 0 AND BODY_CHARS >= 200
 ORDER BY HASH(BUSINESS_ID)
 LIMIT 300;

CREATE TABLE IF NOT EXISTS AI.EVAL_PREDICTIONS (
    VARIANT      VARCHAR(50),
    BUSINESS_ID  NUMBER(38,0),
    PREDICTED    ARRAY,
    PREDICTED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE TABLE AI.EVAL_INPUT AS
SELECT b.BUSINESS_ID, b.TITLE_DE || '\\n' || LEFT(COALESCE(b.BODY_DE, ''), 1500) AS TXT
  FROM AI.EVAL_SAMPLE s JOIN CORE.BUSINESS b ON b.BUSINESS_ID = s.BUSINESS_ID;

-- v0: majority baseline (no AI) -----------------------------------------
DELETE FROM AI.EVAL_PREDICTIONS WHERE VARIANT = 'v0_majority_baseline';
INSERT INTO AI.EVAL_PREDICTIONS (VARIANT, BUSINESS_ID, PREDICTED)
SELECT 'v0_majority_baseline', i.BUSINESS_ID, top2.T
  FROM AI.EVAL_INPUT i,
       (SELECT ARRAY_AGG(TOPIC_EN) WITHIN GROUP (ORDER BY N DESC) AS T
          FROM (SELECT TOPIC_EN, COUNT(*) AS N
                  FROM CORE.BUSINESS_TOPIC GROUP BY 1 ORDER BY 2 DESC LIMIT 2)) top2;

-- v1: labels only --------------------------------------------------------
DELETE FROM AI.EVAL_PREDICTIONS WHERE VARIANT = 'v1_classify_labels';
INSERT INTO AI.EVAL_PREDICTIONS (VARIANT, BUSINESS_ID, PREDICTED)
SELECT 'v1_classify_labels', BUSINESS_ID,
       AI_CLASSIFY(TXT,
                {labels},
                {{'output_mode': 'multi'}}):labels::ARRAY
  FROM AI.EVAL_INPUT;

-- v2: labels + descriptions ---------------------------------------------
DELETE FROM AI.EVAL_PREDICTIONS WHERE VARIANT = 'v2_classify_described';
INSERT INTO AI.EVAL_PREDICTIONS (VARIANT, BUSINESS_ID, PREDICTED)
SELECT 'v2_classify_described', BUSINESS_ID,
       AI_CLASSIFY(TXT,
                {objs},
                {{'output_mode': 'multi'}}):labels::ARRAY
  FROM AI.EVAL_INPUT;

-- v3: labels + descriptions + task description -------------------------
DELETE FROM AI.EVAL_PREDICTIONS WHERE VARIANT = 'v3_classify_task';
INSERT INTO AI.EVAL_PREDICTIONS (VARIANT, BUSINESS_ID, PREDICTED)
SELECT 'v3_classify_task', BUSINESS_ID,
       AI_CLASSIFY(TXT,
                {objs},
                {{'output_mode': 'multi',
                 'task_description': '{TASK}'}}):labels::ARRAY
  FROM AI.EVAL_INPUT;

-- v4: general LLM with a JSON schema (structured output) ----------------
DELETE FROM AI.EVAL_PREDICTIONS WHERE VARIANT = 'v4_complete_json';
INSERT INTO AI.EVAL_PREDICTIONS (VARIANT, BUSINESS_ID, PREDICTED)
SELECT 'v4_complete_json', BUSINESS_ID,
       AI_COMPLETE(
           model => 'llama3.1-70b',  -- llama3.3-70b is not offered in AWS_EU cross-region inference
           prompt => 'Pick the policy topics (usually 2 or 3) of this Swiss parliamentary item. '
                  || 'Allowed topics:\\n{topic_list}\\n\\nItem (German):\\n' || TXT,
           model_parameters => {{'temperature': 0, 'max_tokens': 200}},
           response_format => {{
               'type': 'json',
               'schema': {{
                   'type': 'object',
                   'properties': {{
                       'topics': {{
                           'type': 'array',
                           'items': {{'type': 'string',
                                     'enum': {labels}}}
                       }}
                   }},
                   'required': ['topics']
               }}
           }}
       ):topics::ARRAY
  FROM AI.EVAL_INPUT;

-- Metrics ----------------------------------------------------------------
CREATE OR REPLACE VIEW AI.V_EVAL_PAIRS AS
WITH variants AS (SELECT DISTINCT VARIANT FROM AI.EVAL_PREDICTIONS),
gold AS (
    SELECT v.VARIANT, t.BUSINESS_ID, t.TOPIC_EN AS TOPIC
      FROM AI.EVAL_SAMPLE s
      JOIN CORE.BUSINESS_TOPIC t ON t.BUSINESS_ID = s.BUSINESS_ID
     CROSS JOIN variants v
),
pred AS (
    SELECT p.VARIANT, p.BUSINESS_ID, f.VALUE::VARCHAR AS TOPIC
      FROM AI.EVAL_PREDICTIONS p, LATERAL FLATTEN(INPUT => p.PREDICTED) f
)
SELECT COALESCE(p.VARIANT, g.VARIANT)         AS VARIANT,
       COALESCE(p.BUSINESS_ID, g.BUSINESS_ID) AS BUSINESS_ID,
       COALESCE(p.TOPIC, g.TOPIC)             AS TOPIC,
       p.TOPIC IS NOT NULL                    AS IS_PREDICTED,
       g.TOPIC IS NOT NULL                    AS IS_GOLD
  FROM pred p
  FULL OUTER JOIN gold g
    ON p.VARIANT = g.VARIANT AND p.BUSINESS_ID = g.BUSINESS_ID AND p.TOPIC = g.TOPIC;

CREATE OR REPLACE VIEW AI.V_EVAL_METRICS AS
WITH c AS (
    SELECT VARIANT,
           COUNT_IF(IS_PREDICTED AND IS_GOLD)     AS TP,
           COUNT_IF(IS_PREDICTED AND NOT IS_GOLD) AS FP,
           COUNT_IF(NOT IS_PREDICTED AND IS_GOLD) AS FN
      FROM AI.V_EVAL_PAIRS GROUP BY VARIANT
),
per_item AS (
    SELECT VARIANT, BUSINESS_ID,
           COUNT_IF(IS_PREDICTED) AS N_PRED,
           COUNT_IF(IS_GOLD)      AS N_GOLD,
           COUNT_IF(IS_PREDICTED <> IS_GOLD) = 0 AS EXACT
      FROM AI.V_EVAL_PAIRS GROUP BY VARIANT, BUSINESS_ID
),
failed AS (
    SELECT VARIANT, COUNT_IF(PREDICTED IS NULL) AS FAILED_CALLS
      FROM AI.EVAL_PREDICTIONS GROUP BY VARIANT
)
SELECT c.VARIANT,
       c.TP, c.FP, c.FN,
       ROUND(c.TP / NULLIF(c.TP + c.FP, 0), 3)                AS PRECISION,
       ROUND(c.TP / NULLIF(c.TP + c.FN, 0), 3)                AS RECALL,
       ROUND(2 * c.TP / NULLIF(2 * c.TP + c.FP + c.FN, 0), 3) AS F1,
       ROUND(AVG(IFF(i.EXACT, 1, 0)), 3)                      AS EXACT_SET_MATCH,
       ROUND(AVG(i.N_PRED), 2)                                AS AVG_PREDICTED_TOPICS,
       ROUND(AVG(i.N_GOLD), 2)                                AS AVG_OFFICIAL_TOPICS,
       ANY_VALUE(f.FAILED_CALLS)                              AS FAILED_CALLS
  FROM c
  JOIN per_item i ON i.VARIANT = c.VARIANT
  LEFT JOIN failed f ON f.VARIANT = c.VARIANT
 GROUP BY c.VARIANT, c.TP, c.FP, c.FN
 ORDER BY F1 DESC;

CREATE OR REPLACE VIEW AI.V_EVAL_TOPIC_F1 AS
SELECT VARIANT, TOPIC,
       COUNT_IF(IS_GOLD)      AS OFFICIAL_COUNT,
       COUNT_IF(IS_PREDICTED) AS PREDICTED_COUNT,
       ROUND(2 * COUNT_IF(IS_PREDICTED AND IS_GOLD)
             / NULLIF(COUNT_IF(IS_PREDICTED) + COUNT_IF(IS_GOLD), 0), 3) AS F1
  FROM AI.V_EVAL_PAIRS
 GROUP BY VARIANT, TOPIC;

SELECT * FROM AI.V_EVAL_METRICS;
"""

out = ROOT / "snowflake" / "04_cortex_eval.sql"
out.write_text(sql, encoding="utf-8")
print(f"wrote {out} ({len(sql.splitlines())} lines, {len(rows)} topics)")
